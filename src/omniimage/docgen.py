"""Generate the node reference documentation straight from the registry (so it can never go stale)."""
from __future__ import annotations
from .core.registry import list_specs


def node_reference() -> str:
    specs = list_specs()
    lines = ["# Node reference", "", f"{len(specs)} built-in node types. Generated by `omni docs`; do not edit by hand.", "",
             "Legend: **LUT-safe** nodes are color-only and per-pixel, so a chain made only of them can be baked into a "
             "`.cube` LUT.", ""]
    cat = None
    for s in specs:
        if s.category != cat:
            cat = s.category
            lines += [f"## {cat}", ""]
        lines.append(f"### `{s.type}`" + ("  (LUT-safe)" if s.pointwise else ""))
        lines += ["", s.doc, ""]
        if s.inputs or s.outputs:
            ins = ", ".join(f"`{k}`:{v.value}" + ("?" if k in s.optional else "") for k, v in s.inputs.items()) or "none"
            outs = ", ".join(f"`{k}`:{v.value}" for k, v in s.outputs.items()) or "none (sink)"
            lines += [f"- inputs: {ins}", f"- outputs: {outs}"]
        if s.params:
            lines += ["", "| parameter | type | default | range / choices | notes |", "|---|---|---|---|---|"]
            for k, p in s.params.items():
                rng = ", ".join(p.choices) if p.choices else (f"{p.min}..{p.max}" if p.min is not None or p.max is not None else "")
                lines.append(f"| `{k}` | {p.type} | `{p.default}` | {rng} | {p.doc} |")
        lines.append("")
    return "\n".join(lines)
